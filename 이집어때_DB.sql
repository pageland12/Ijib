CREATE TABLE MEMBER(
    mno         NUMBER(6),
    memail      VARCHAR2(200) NOT NULL UNIQUE,
    mpasswd     VARCHAR2(200) NOT NULL,
    mname       VARCHAR2(30) NOT NULL,
    mgender     VARCHAR2(10) NOT NULL,
    mage        NUMBER(3) NOT NULL,
    maddr       VARCHAR2(1000) NOT NULL,
    mtel        VARCHAR2(15) NOT NULL,
    maccount    VARCHAR2(1000) NOT NULL,
    mauth       VARCHAR2(30) DEFAULT 'NORMAL',
    mstatus     VARCHAR2(200) DEFAULT 'ACTIVE',
    mdate       DATE DEFAULT SYSDATE,
    
    CONSTRAINT PK_MEMBER PRIMARY KEY(mno)
);

